// Generates the API types from the committed OpenAPI documents: src/api/schema.d.ts from the
// controller's (openapi.json) and src/api/portal-schema.d.ts from the portal's
// (portal-openapi.json).
//
// Called through the library rather than the CLI: the CLI resolves its input as a URL,
// so a checkout under a folder with '#' in its name (such as "C#") loses everything
// after the '#'. Handing it the parsed document avoids path resolution entirely.
import { readFile, writeFile } from 'node:fs/promises'
import openapiTS, { astToString } from 'openapi-typescript'

for (const [source, target] of [
  ['openapi.json', 'schema.d.ts'],
  ['portal-openapi.json', 'portal-schema.d.ts'],
]) {
  const document = JSON.parse(await readFile(new URL(`../src/api/${source}`, import.meta.url), 'utf8'))
  const ast = await openapiTS(document)
  const header = `// Generated by \`npm run gen:api\` from src/api/${source}. Do not edit.\n\n`
  await writeFile(new URL(`../src/api/${target}`, import.meta.url), header + astToString(ast))
  console.log(`Wrote src/api/${target}`)
}
